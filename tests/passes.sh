#!/usr/bin/env bash
# Checks run_pi (failure stops the run) and assemble_review (what gets posted), with a stub pi.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
stub=$(mktemp -d)
sed -n '/^# ── passes/,/^# ── end passes/p' "$root/gh-pr-review" >"$stub/lib.sh"
footer='*Review generated by gh pr-review · model: m*'
# The script must reach its end: Bash 3.2 can stop on an error inside an EXIT trap with status 0.
finished=false
trap '[[ $finished == true ]] || { echo "FAIL stopped before the end"; exit 1; }' EXIT
fail=0

eq() { # name got want
	if [[ "$2" == "$3" ]]; then echo "ok   $1"; else
		printf 'FAIL %s:\n got: %q\nwant: %q\n' "$1" "$2" "$3"
		fail=1
	fi
}

in_lib() { # script (runs with lib sourced and the stub pi on PATH)
	PATH="$stub:$PATH" bash -c "set -euo pipefail; source '$stub/lib.sh'; SESSION_DIR='$stub' MODEL=m; $1" 2>&1 ||
		echo "(exit $?)"
}

printf 'PROMPT' >"$stub/p.md"
# shellcheck disable=SC2016 # the stub must expand $* when it runs, not now
printf '#!/usr/bin/env bash\necho "out:${*: -1}"\n' >"$stub/pi"
chmod +x "$stub/pi"
in_lib "PI_ARGS=(--print); run_pi '$stub/p.md' '$stub/o.md'" >/dev/null
eq "run_pi writes pi output" "$(cat "$stub/o.md" 2>/dev/null || true)" "out:PROMPT"

printf '#!/usr/bin/env bash\nexit 3\n' >"$stub/pi"
out=$(in_lib "PI_ARGS=(); run_pi '$stub/p.md' '$stub/o.md'; echo SHOULD-NOT-REACH")
eq "run_pi failure exits" "$([[ "$out" == *"(exit 1)"* && "$out" != *SHOULD-NOT-REACH* ]] && echo y)" y
eq "run_pi failure names the session" "$([[ "$out" == *"$stub"* ]] && echo y)" y

boundary='<!-- gh-pr-review:code-review -->'
eq "approach, boundary, review, footer" "$(in_lib "assemble_review '' 'APPROACH' 'REVIEW'")" \
	$'APPROACH\n\n'"$boundary"$'\nREVIEW\n\n---\n'"$footer"
eq "loop line first" "$(in_lib "assemble_review 'LOOP' 'APPROACH' 'REVIEW'")" \
	$'LOOP\n\nAPPROACH\n\n'"$boundary"$'\nREVIEW\n\n---\n'"$footer"
eq "skip-approach: boundary, review and footer" "$(in_lib "assemble_review '' '' 'REVIEW'")" \
	"$boundary"$'\nREVIEW\n\n---\n'"$footer"
eq "rethink: approach and footer, no boundary" "$(in_lib "assemble_review '' 'APPROACH' ''")" $'APPROACH\n\n---\n'"$footer"
eq "nothing to post stays empty" "$(in_lib "assemble_review '' '' ''")" ""
finished=true
exit "$fail"
